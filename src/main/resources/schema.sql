DROP TABLE IF EXISTS product_import_error;
DROP TABLE IF EXISTS daily_sales_summary;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS product;
DROP TABLE IF EXISTS customer;

-- 고객 (06 장: 고객 등급 산정 대상)
CREATE TABLE customer
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50)  NOT NULL,
    email      VARCHAR(100) NOT NULL UNIQUE,
    grade      VARCHAR(20)  NOT NULL DEFAULT 'BRONZE',
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 상품 (05, 08 장: CSV 파일 -> DB 적재 대상)
CREATE TABLE product
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30)  NOT NULL UNIQUE,
    name       VARCHAR(100) NOT NULL,
    price      BIGINT       NOT NULL,
    stock      INT          NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 주문
CREATE TABLE orders
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT      NOT NULL REFERENCES customer (id),
    amount      BIGINT      NOT NULL,
    status      VARCHAR(20) NOT NULL,
    ordered_at  TIMESTAMP   NOT NULL
);

CREATE INDEX idx_orders_ordered_at ON orders (ordered_at);
CREATE INDEX idx_orders_customer_id ON orders (customer_id);

-- 일별 매출 집계 결과 (07 장)
CREATE TABLE daily_sales_summary
(
    sales_date   DATE      NOT NULL PRIMARY KEY,
    order_count  INT       NOT NULL,
    total_amount BIGINT    NOT NULL,
    created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 상품 적재 중 Skip 된 데이터 기록 (08 장)
CREATE TABLE product_import_error
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phase      VARCHAR(10)   NOT NULL,
    item       VARCHAR(500),
    reason     VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
